def main():
    raw = io.open(CL, 'rb').read()
    shutil.copy2(CL, BAK)
    text = raw.decode('utf-8')
    assert text.endswith('\n'), 'unexpected: file does not end with LF'
    assert u'0.290.7' not in text, 'already appended?'
    new = text + '\n' + SECTION
    io.open(CL, 'w', encoding='utf-8', newline='').write(new)

    # 核验：前缀完全一致 + 新段可读
    back = io.open(CL, 'rb').read()
    assert back[:len(raw)] == raw, 'prefix changed!'
    added = len(back) - len(raw)
    print('备份      : %s' % BAK)
    print('追加前    : %d 字节' % len(raw))
    print('追加后    : %d 字节（+%d）' % (len(back), added))
    print('十六 段存在: %s' % (u'十六、0.290.7 beta21.7' in back.decode('utf-8')))
    print('旧段未动  : %s' % (u'十五、30 系 GCU 适配与多项修复' in back.decode('utf-8')))
    return 0


if __name__ == '__main__':
    sys.exit(main())
